-- 5. Storage RLS Policies (Run this after creating the 'downloads' bucket manually)
-- These allow the service role to manage objects in the 'downloads' bucket.

INSERT INTO storage.buckets (id, name, public) 
VALUES ('downloads', 'downloads', false)
ON CONFLICT (id) DO NOTHING;

CREATE POLICY "Service Role Full Access" ON storage.objects
    FOR ALL 
    TO service_role
    USING (bucket_id = 'downloads')
    WITH CHECK (bucket_id = 'downloads');
