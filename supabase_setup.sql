-- 1. Create the jobs table
CREATE TABLE IF NOT EXISTS public.jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz DEFAULT now() NOT NULL,
    status text DEFAULT 'queued' NOT NULL,
    progress float8 DEFAULT 0 NOT NULL,
    message text,
    title text,
    file_path text,
    log text,
    url text NOT NULL
);

-- 2. Enable Row Level Security (RLS) for jobs
ALTER TABLE public.jobs ENABLE ROW LEVEL SECURITY;

-- 3. Create a policy that allows all operations (Service Role will bypass this anyway)
CREATE POLICY "Allow service role full access" ON public.jobs
    FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);

